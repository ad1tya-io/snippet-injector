import * as vscode from 'vscode';
import * as path from 'path';
import { DeliveryMethod, DerivedArtifact, SelectionContext } from '../types/pipeline';

export class Inserter {
  /**
   * Delivers the derived artifact to the target destination using WorkspaceEdit or clipboard.
   */
  public static async deliver(
    artifact: DerivedArtifact,
    method: DeliveryMethod,
    ctx: SelectionContext
  ): Promise<boolean> {
    switch (method) {
      case 'inline-below':
        return this.insertInlineBelow(artifact, ctx);
      case 'companion-file':
        return this.insertIntoCompanionFile(artifact, ctx);
      case 'clipboard':
        return this.copyToClipboard(artifact);
      default:
        throw new Error(`Unsupported delivery method: ${method}`);
    }
  }

  /**
   * Inserts text immediately below selection line using vscode.WorkspaceEdit.
   */
  private static async insertInlineBelow(
    artifact: DerivedArtifact,
    ctx: SelectionContext
  ): Promise<boolean> {
    const editor = vscode.window.activeTextEditor;
    if (!editor) {
      vscode.window.showWarningMessage('No active editor to insert code into.');
      return false;
    }

    const document = editor.document;
    const insertLine = ctx.endLine + 1;
    const insertPosition = new vscode.Position(insertLine, 0);

    // Prepare insertion content with leading and trailing newlines
    const formattedCode = `\n${artifact.code}\n`;

    const edit = new vscode.WorkspaceEdit();
    if (insertLine >= document.lineCount) {
      const lastLine = document.lineAt(document.lineCount - 1);
      edit.insert(document.uri, lastLine.range.end, formattedCode);
    } else {
      edit.insert(document.uri, insertPosition, formattedCode);
    }

    const applied = await vscode.workspace.applyEdit(edit);

    if (applied) {
      // Attempt range formatting if provider is available
      try {
        const startPos = new vscode.Position(insertLine, 0);
        const endPos = new vscode.Position(insertLine + artifact.code.split('\n').length, 0);
        const range = new vscode.Range(startPos, endPos);

        const textEdits = await vscode.commands.executeCommand<vscode.TextEdit[]>(
          'vscode.executeFormatRangeProvider',
          document.uri,
          range,
          { tabSize: editor.options.tabSize || 2, insertSpaces: Boolean(editor.options.insertSpaces) }
        );

        if (textEdits && textEdits.length > 0) {
          const formatEdit = new vscode.WorkspaceEdit();
          formatEdit.set(document.uri, textEdits);
          await vscode.workspace.applyEdit(formatEdit);
        }
      } catch {
        // Formatting provider might not be registered for language; fallback gracefully
      }
    }

    return applied;
  }

  /**
   * Creates or opens a companion file (e.g. UserService.spec.ts for UserService.ts)
   * and inserts the generated artifact using vscode.WorkspaceEdit.
   */
  private static async insertIntoCompanionFile(
    artifact: DerivedArtifact,
    ctx: SelectionContext
  ): Promise<boolean> {
    const sourceDir = path.dirname(ctx.filePath);
    const suggestedFileName = artifact.suggestedFileName || `${ctx.fileBaseName}.spec.ts`;
    const companionPath = path.join(sourceDir, suggestedFileName);
    const companionUri = vscode.Uri.file(companionPath);

    const edit = new vscode.WorkspaceEdit();

    // Check if companion file exists
    let exists = false;
    try {
      await vscode.workspace.fs.stat(companionUri);
      exists = true;
    } catch {
      exists = false;
    }

    if (!exists) {
      // Create empty companion file entry
      edit.createFile(companionUri, { ignoreIfExists: true, overwrite: false });
      const header = `// Derived snippet generated by Snippet Injector from ${path.basename(ctx.filePath)}\n\n`;
      edit.insert(companionUri, new vscode.Position(0, 0), header + artifact.code + '\n');
    } else {
      // Append to end of existing file
      const doc = await vscode.workspace.openTextDocument(companionUri);
      const endPos = new vscode.Position(doc.lineCount, 0);
      edit.insert(companionUri, endPos, `\n\n${artifact.code}\n`);
    }

    const applied = await vscode.workspace.applyEdit(edit);
    if (applied) {
      const doc = await vscode.workspace.openTextDocument(companionUri);
      await vscode.window.showTextDocument(doc, { preview: false });
    }

    return applied;
  }

  /**
   * Copies snippet to system clipboard.
   */
  private static async copyToClipboard(artifact: DerivedArtifact): Promise<boolean> {
    await vscode.env.clipboard.writeText(artifact.code);
    vscode.window.showInformationMessage(`Snippet (${artifact.generatorName}) copied to clipboard!`);
    return true;
  }
}
